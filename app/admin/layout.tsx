            onClick={handleLogout}
            disabled={loggingOut}
            className="w-full flex items-center gap-2 px-3 py-2 rounded-lg text-xs text-slate-500 hover:text-red-600 hover:bg-red-50 transition-colors disabled:opacity-50 text-left"
